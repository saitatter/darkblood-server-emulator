#!/usr/bin/env python3
"""Generate docs/OPCODE_REGISTRY.md from the client opcode table and the server code.

Sources:
  assets/opcodes.tsv                 client enum names (extracted from the binary)
  research/client/handler_map.txt    client handler VAs (written by the shim; optional, local only)
  darkblood.games.session.DISPATCHER server handlers (on_<opcode> methods)
  darkblood.games.network.messages   message classes whose docstring starts with "Opcode N"

Only opcodes with at least one of a client handler, a server handler or a
message class are listed. Run from the repository root:
    python tools/codegen/gen_opcode_registry.py
"""
import inspect
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'src'))

from darkblood.games import session  # noqa: E402  (registers every controller)
from darkblood.games.network import messages  # noqa: E402

OUTPUT = ROOT / 'docs' / 'OPCODE_REGISTRY.md'
RANGES = [
    (0, 1999, 'System and ProudNet core'),
    (2000, 2999, 'Game server (eEGS)'),
    (3000, 4999, 'Database and other services'),
    (5000, 5999, 'Room and relay server (eERC)'),
    (6000, 99999, 'Other'),
]


def client_names():
    names = {}
    for line in (ROOT / 'assets' / 'opcodes.tsv').read_text(encoding='utf-8').splitlines():
        parts = line.split('\t')
        if len(parts) >= 2 and parts[0].isdigit():
            names[int(parts[0])] = parts[1]
    return names


def client_handlers():
    path = ROOT / 'research' / 'client' / 'handler_map.txt'
    handlers = {}
    if not path.is_file():
        return handlers
    for line in path.read_text(encoding='utf-8', errors='replace').splitlines():
        parts = line.split()
        if len(parts) >= 4:
            handlers[int(parts[1], 16)] = '0x%s' % parts[3].upper()
    return handlers


def first_line(text):
    for line in (text or '').strip().splitlines():
        line = line.strip().lstrip('#').strip()
        if line:
            return line.replace('|', '\\|')
    return ''


def server_handlers():
    out = {}
    for opcode, (_, handler) in session.DISPATCHER._handlers.items():
        parts = handler.__module__.split('.')
        if len(parts) >= 2 and parts[-2] != 'handlers':
            module = f'{parts[-2]}/{parts[-1]}.py'
        else:
            module = parts[-1] + '.py'
        label = f'`{module}` (`{handler.__name__}`)'
        doc = handler.__doc__
        if not doc:
            try:
                body = inspect.getsource(handler).splitlines()[1:]
                doc = '\n'.join(l for l in body if l.strip().startswith('#'))
            except (OSError, TypeError):
                doc = ''
        out[opcode] = (label, first_line(doc))
    return out


def message_classes():
    out = {}
    for name, obj in vars(messages).items():
        if inspect.isclass(obj) and obj.__doc__:
            match = re.match(r'\s*Opcodes? (\d+)', obj.__doc__)
            if match:
                out.setdefault(int(match.group(1)), []).append(name)
    return out


def main(argv=None):
    args = sys.argv[1:] if argv is None else argv
    check = '--check' in args
    names, client, server, classes = client_names(), client_handlers(), server_handlers(), message_classes()
    tracked = sorted(set(client) | set(server) | set(classes))
    lines = [
        '# Opcode registry',
        '',
        '> Generated by `tools/codegen/gen_opcode_registry.py`; do not edit by hand. Enum names come',
        '> from the client (`assets/opcodes.tsv`), client handler addresses from the shim\'s',
        '> `handler_map.txt` when present, server handlers from the startup dispatcher.',
        '',
        f'**Tracked opcodes**: {len(tracked)}  ',
        f'**Client handlers mapped**: {len(client)}  ',
        f'**Server handlers**: {len(server)}  ',
        '',
        'Wire rules are in `docs/PROTOCOL.md`.',
        '',
    ]
    for low, high, title in RANGES:
        rows = [op for op in tracked if low <= op <= high]
        if not rows:
            continue
        lines += [f'## {title} ({low}-{high})', '',
                  '| Opcode | Enum name | Client handler | Server handler | Messages | Notes |',
                  '| ---: | :--- | :--- | :--- | :--- | :--- |']
        for op in rows:
            module, note = server.get(op, ('—', ''))
            msg = ', '.join(f'`{c}`' for c in sorted(classes.get(op, []))) or '—'
            lines.append(f'| {op} | `{names.get(op, "?")}` | {client.get(op, "—")} | {module} | {msg} | {note} |')
        lines.append('')
    rendered = '\n'.join(lines)
    if check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.is_file() else ''
        if current != rendered:
            print(f'{OUTPUT.relative_to(ROOT)} is stale; run python tools/codegen/gen_opcode_registry.py', file=sys.stderr)
            return 1
        print(f'{OUTPUT.relative_to(ROOT)} is current ({len(tracked)} opcodes, {len(server)} server handlers)')
        return 0
    OUTPUT.write_text(rendered, encoding='utf-8')
    print(f'Wrote {OUTPUT.relative_to(ROOT)}: {len(tracked)} opcodes, {len(server)} server handlers')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
